"""Build the technical report from result directories, so every number in it comes from a file.

    sciagent report results/cpu [results/gpu ...] --out docs/TECHNICAL_REPORT.md

Each root is a directory produced by ``sciagent experiments`` (steps env, verify, gpu_bench, bench_cpu, surrogate,
bench_llm, traces, train_student, inference, bench_distill). Missing steps are listed as not run.
"""

from __future__ import annotations

import json
import math
import time
from pathlib import Path

from . import __version__
from .simulators import get_simulator, references


def _j(p: Path):
    try:
        return json.loads(p.read_text())
    except Exception:
        return None


def _f(x, d=4):
    if x is None or (isinstance(x, float) and (math.isnan(x) or math.isinf(x))):
        return "–"
    return f"{x:.{d}g}"


def _find(roots: list[Path], rel: str) -> Path | None:
    for r in roots:
        if (r / rel).exists():
            return r / rel
    return None


def _analysis_tables(a: dict, title: str) -> list[str]:
    L = [f"### {title}", ""]
    for t, r in a["tasks"].items():
        L += [f"**{t}**", "", "| planner | mean regret | 95% CI | median | solved | AUC log10 | p vs best (Holm) |",
              "|---|---|---|---|---|---|---|"]
        for p, s in sorted(r["stats"].items(), key=lambda kv: kv[1]["mean"]):
            pv = "best" if p == r["best"] else _f(r["holm_vs_best"].get(p), 2)
            if pv == "–" and p != r["best"]:
                pv = "n < 5: no test"
            L.append(f"| {p} | {_f(s['mean'])} | [{_f(s['ci95'][0])}, {_f(s['ci95'][1])}] | {_f(s['median'])} | "
                     f"{s['success_rate']:.0%} of {s['n']} | {_f(s['auc_log10_regret'], 3)} | {pv} |")
        for p, k in r.get("no_result", {}).items():
            L.append(f"| {p} | no valid result in {k} studies | | | | | |")
        L.append("")
    return L


def _findings(analyses: list[tuple[str, dict]]) -> list[str]:
    out = []
    for label, a in analyses:
        for t, r in a["tasks"].items():
            best = r["best"]
            tested = {p: q for p, q in r["holm_vs_best"].items() if q is not None}
            sig = [p for p, q in tested.items() if q < 0.05]
            ns = [p for p in tested if p not in sig]
            untested = [p for p in r["stats"] if p != best and p not in tested]
            s = f"{label}, **{t}**: lowest mean regret by `{best}` ({_f(r['stats'][best]['mean'], 3)})"
            if sig:
                s += f"; significantly better than {', '.join(f'`{p}`' for p in sig)} (Holm p < 0.05)"
            if ns:
                s += f"; not significantly different from {', '.join(f'`{p}`' for p in ns)}"
            if untested:
                s += f"; too few paired seeds to test against {', '.join(f'`{p}`' for p in untested)}"
            if r.get("no_result"):
                s += f"; no valid result from {', '.join(f'`{p}`' for p in r['no_result'])}"
            out.append("- " + s + ".")
    return out


def build(roots: list[str | Path], out: str | Path) -> str:
    roots = [Path(r) for r in roots]
    env = [(_j(r / "env" / "env.json"), r) for r in roots if (r / "env" / "env.json").exists()]
    L = ["# SciAgent-Bench: technical report", "",
         f"Generated by `sciagent report` (v{__version__}) on {time.strftime('%Y-%m-%d')} from: "
         + ", ".join(f"`{r}`" for r in roots) + ". Every number below is read from those result files.", ""]

    # ---------------------------------------------------------------- abstract / findings
    analyses = []
    for r in roots:
        for b in sorted((r / "bench_cpu").glob("b*/analysis/analysis.json")) if (r / "bench_cpu").exists() else []:
            analyses.append((f"Classical planners, budget {b.parent.parent.name[1:]}", _j(b)))
    llm_a = _find(roots, "bench_llm/analysis/analysis.json")
    if llm_a:
        analyses.append(("LLM planners", _j(llm_a)))
    dis_a = _find(roots, "bench_distill/analysis/analysis.json")
    if dis_a:
        analyses.append(("Distilled planner", _j(dis_a)))
    L += ["## Summary", "",
          "SciAgent-Bench evaluates planners that decide which simulations to run, and at which fidelity, under a fixed "
          "compute budget. Three scientific tasks with verified reference optima are used: a chemical batch reactor "
          "(exact optimum; cheap solvers are biased), a 2-D heat-conduction design problem (grid fidelity) and a MIMO "
          "energy-efficiency problem (noisy Monte-Carlo fidelity). The score is the regret of the design each planner "
          "would report. Key results:", ""]
    L += _findings(analyses) or ["- No benchmark results found."]
    L.append("")

    # ---------------------------------------------------------------- environment
    L += ["## 1. Environment", ""]
    for e, r in env:
        d = e.get("device", {})
        pk = e.get("packages", {})
        L.append(f"- `{r.name}` (profile `{e.get('profile')}`): device **{d.get('name', d.get('device'))}**"
                 + (f" x{d.get('count')}" if d.get("count") else "") + f", Python {e['environment'].get('python')}, "
                 + ", ".join(f"{k} {v}" for k, v in pk.items() if v) + f", git `{e['environment'].get('git_sha') or 'n/a'}`.")
    if not env:
        L.append("- No environment records found.")
    L.append("")

    # ---------------------------------------------------------------- tasks & references
    L += ["## 2. Tasks and reference solutions", "", "| task | parameters | fidelities (cost) | reference optimum | type |",
          "|---|---|---|---|---|"]
    refs = references()
    for name in ("reactor", "heat", "mimo"):
        sim = get_simulator(name)
        ref = refs.get(name, {})
        L.append(f"| {name} | " + ", ".join(f"{p.name} [{p.low:g}, {p.high:g}]{' ' + p.unit if p.unit else ''}" for p in sim.params)
                 + " | " + ", ".join(f"{f.name} ({f.cost:g})" for f in sim.fidelities)
                 + f" | {_f(ref.get('optimum'), 8)} | {'exact' if ref.get('exact') else 'best known'} |")
    v = _find(roots, "verify/references_verification.json")
    if v:
        vr = _j(v)
        L += ["", f"Verification (`{v.parent.parent.name}`, device {vr['device'].get('name', vr['device']['device'])}):", ""]
        re_ = vr["reactor"]
        L.append(f"- **reactor**: scaled gradient norm {re_['grad_norm_scaled']:.1e} at the closed-form optimum; Hessian "
                 f"eigenvalues all negative: {re_['is_strict_local_max']}.")
        he = vr["heat"]
        L.append(f"- **heat**: {len(he['search_values'])} independent global searches agree to {he['search_spread']:.1e}; "
                 f"the reference exceeds the best of them by {he['reference_minus_best_search']:+.1e}.")
        if "observed_order" in he:
            L.append(f"  Grid convergence at the optimal design up to n = {he['convergence'][-1]['n']}: observed order "
                     f"{he['observed_order']:.2f}, Richardson continuum value {he['richardson_continuum']:.6f}; the grid64 "
                     f"task definition differs from it by {he['grid64_discretisation_error']:+.2e}. Most of that gap comes from "
                     "the pin's diffuse-interface width, which is tied to the grid below n = 127; it is a property of "
                     "the task definition, not an error in scoring.")
        mi = vr["mimo"]
        L.append(f"- **mimo**: with {mi['draws']:,} draws the reference design scores {mi['high_precision_value']:.5f} "
                 f"± {mi['high_precision_stderr']:.1e}; the scoring estimator (40k draws, fixed seed) differs by "
                 f"{mi['estimator_bias_40k_vs_high_precision']:+.1e}. The best antenna count beats the runner-up "
                 f"(n_tx = {mi['runner_up']['n_tx']}) by {mi['gap_to_runner_up']:.4f} (z = {mi['gap_z']:.0f}).")
    L.append("")

    # ---------------------------------------------------------------- methods
    L += ["## 3. Methods", "",
          "**Planners.** `random`: uniform sampling at the top fidelity. `sh`: budget-aware successive halving across "
          "fidelities (eta = 3). `bo`: Gaussian-process Bayesian optimisation (Matern 5/2, expected improvement, batched by "
          "kriging believer) at the top fidelity. `scripted-mf`: a hand-written explore-refine-confirm multi-fidelity "
          "policy run through the full LLM-agent code path with a deterministic mock model (a baseline, not an LLM). "
          "LLM planners receive the researcher's goal, the simulator card, budget state, the run history and optional "
          "tool outputs (GP suggestions), and must return a JSON plan.", "",
          "**Budget enforcement.** Planners only propose. A deterministic guard enforces bounds, fidelity names, batch "
          "size and the remaining budget through a reserve/commit ledger; property-based tests check that no proposal "
          "can overspend. LLM spend is capped before each call using a worst-case estimate.", "",
          "**Metric.** Regret = reference optimum minus the noise-free objective of the reported incumbent (the best "
          "result at the highest fidelity evaluated). AUC = mean log10 regret over the budget (anytime performance).", "",
          "**Statistics.** Seeded bootstrap 95% CIs of the mean (10,000 resamples); paired Wilcoxon signed-rank tests "
          "over seeds against the best planner per task with Holm correction; success = regret below a task tolerance.",
          "", "**Reproducibility.** Seeds derive from (study seed, run index); every run records its spec, environment "
          "and a results digest. LLM calls are recorded to cassettes so that LLM-driven campaigns replay exactly; "
          "interrupted studies resume by fast-forwarding recorded runs.", ""]

    # ---------------------------------------------------------------- results
    L += ["## 4. Results", ""]
    for label, a in analyses:
        L += _analysis_tables(a, label)
    for r in roots:
        for png in sorted((r / "bench_cpu").glob("b*/regret_curves.png")) if (r / "bench_cpu").exists() else []:
            L.append(f"Median regret curves: `{png}`")
    L.append("")
    llm_srv = _find(roots, "bench_llm/server.json")
    if llm_srv:
        s = _j(llm_srv)
        L.append(f"Teacher model: `{s['model']}` served with {s['backend']}.")
        import csv

        rows = list(csv.DictReader(open(llm_srv.parent / "results.csv")))
        by = {}
        for row in rows:
            if row["llm_tokens_in"] not in ("", "0", "None"):
                by.setdefault(row["planner"], []).append((int(row["llm_tokens_in"]), int(row["llm_tokens_out"]),
                                                         float(row["wall_s"])))
        if by:
            L += ["", "| LLM planner | tokens in / study | tokens out / study | wall time / study (s) |", "|---|---|---|---|"]
            for p, v in by.items():
                n = len(v)
                L.append(f"| {p} | {sum(x[0] for x in v) / n:,.0f} | {sum(x[1] for x in v) / n:,.0f} | {sum(x[2] for x in v) / n:.0f} |")
        L.append("")

    # surrogate
    sur = []
    for r in roots:
        for rep in sorted(r.glob("surrogate/models/*/report.json")):
            sur.append(_j(rep))
    if sur:
        L += ["### Surrogate distillation and quantisation", ""]
        for s in sur:
            L += [f"**{s['simulator']}** ({s['test_rows']} held-out rows; trained on "
                  f"{(s.get('train_device') or {}).get('name', (s.get('train_device') or {}).get('device', 'cpu'))}; "
                  f"one top-fidelity simulator call: {s['simulator_top_fidelity_latency_us'] / 1000:.1f} ms)", "",
                  "| model | MAE top fid. | R² top fid. | size (KiB) | latency b=1 (µs) | µs/prediction at b=4096 |", "|---|---|---|---|---|---|"]
            for m in s["models"]:
                size = "–" if m["size_bytes"] is None else f"{m['size_bytes'] / 1024:.1f}"
                L.append(f"| {m['model']} | {_f(m['mae_top_fidelity'])} | {_f(m['r2_top_fidelity'], 4)} | "
                         f"{size} | {m['latency_b1_us']:.0f} | "
                         f"{m['latency_b4096_ms'] * 1e3 / 4096:.3f} |")
            L.append("")

    # GPU kernels
    gb = _find(roots, "gpu_bench/throughput.json")
    if gb:
        g = _j(gb)
        L += [f"### Kernel throughput ({g['device'].get('name', g['device']['device'])})", ""]
        L += ["| MIMO draws | NumPy (s) | torch fp64 (s) | torch fp32 (s) |", "|---|---|---|---|"]
        for x in g["mimo"]:
            L.append(f"| {x['draws']:,} | {_f(x.get('numpy_s'), 3)} | {_f(x['torch_fp64_s'], 3)} | {_f(x['torch_fp32_s'], 3)} |")
        L += ["", "| heat grid | unknowns | SciPy direct (s) | torch PCG (s) | iterations |", "|---|---|---|---|---|"]
        for x in g["heat"]:
            L.append(f"| {x['n']} | {x['unknowns']:,} | {_f(x.get('scipy_direct_s'), 3)} | {_f(x['torch_cg_s'], 3)} | {x['cg_iterations']} |")
        L.append("")

    # distillation
    sft = _find(roots, "traces/make_sft.log")
    ts = _find(roots, "train_student/planner-lora/train_summary.json")
    inf = _find(roots, "inference/inference_summary.json")
    if sft or ts or inf:
        L += ["### Planner distillation and efficient serving", ""]
        if ts:
            t = _j(ts)
            losses = [h["loss"] for h in t["log_history"] if "loss" in h] or \
                [h["train_loss"] for h in t["log_history"] if "train_loss" in h]
            evals = [h["eval_loss"] for h in t["log_history"] if "eval_loss" in h]
            L.append(f"LoRA (rank {t['rank']}) on `{t['base']}`: {t['train']} training / {t['val']} validation plans, "
                     f"{t['epochs']} epoch(s); training loss {_f(losses[0] if losses else None, 3)} -> "
                     f"{_f(losses[-1] if losses else None, 3)}, final validation loss {_f(evals[-1] if evals else None, 3)}.")
        if inf:
            L += ["", "| model | backend | p50 latency (s) | p90 latency (s) | output tok/s (aggregate) | valid JSON plans |",
                  "|---|---|---|---|---|---|"]
            for x in _j(inf):
                if "error" in x:
                    L.append(f"| {x['label']} | failed: {x['error'][:80]} | | | | |")
                else:
                    L.append(f"| {x['label']} | {x.get('backend', '')} | {x['latency_p50_s']:.2f} | {x['latency_p90_s']:.2f} | "
                             f"{x['aggregate_output_tok_per_s']:.0f} | {x['valid_json_plan_rate']:.0%} |")
        L.append("")

    # ---------------------------------------------------------------- status & limitations
    status = {}
    for r in roots:
        for s in ("env", "tests", "verify", "gpu_bench", "bench_cpu", "surrogate", "bench_llm", "traces", "train_student",
                  "inference", "bench_distill"):
            if (r / s / "DONE.json").exists():
                status[s] = r.name
            elif (r / s / "ERROR.txt").exists() and s not in status:
                status[s] = f"failed in {r.name}"
    L += ["## 5. What was run", "", "| step | where |", "|---|---|"]
    for s in ("env", "tests", "verify", "gpu_bench", "bench_cpu", "surrogate", "bench_llm", "traces", "train_student",
              "inference", "bench_distill"):
        L.append(f"| {s} | {status.get(s, 'not run')} |")
    L += ["", "## 6. Limitations", "",
          "- The three tasks are inexpensive stand-ins chosen so that the benchmark and its statistics run in CI; real lab "
          "codes plug in through the simulator template, and conclusions about planners may not transfer to them.",
          "- `heat` and `mimo` references are best-known values with the verification above, not proofs of global "
          "optimality; `reactor` is exact.",
          "- Regret is measured in each task's own units, so values are compared within a task, not across tasks.",
          "- LLM results depend on the model version, serving stack and prompt; they are reproducible from the recorded "
          "cassettes, not from re-querying the model.",
          "- Paired tests match planners by seed. Planners share a seed's random stream only partly, so pairs are "
          "weakly matched: the tests remain valid but have less power than a fully matched design.", ""]
    text = "\n".join(L) + "\n"
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    return text
